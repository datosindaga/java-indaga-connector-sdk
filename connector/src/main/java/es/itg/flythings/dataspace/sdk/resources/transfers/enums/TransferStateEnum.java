package es.itg.flythings.dataspace.sdk.resources.transfers.enums;

/**
 * Enumerates lifecycle states for a data transfer.
 */
public enum TransferStateEnum {

    /**
     * Requested transfer state enum.
     */
    REQUESTED,
    /**
     * Started transfer state enum.
     */
    STARTED,
    /**
     * Suspended transfer state enum.
     */
    SUSPENDED,
    /**
     * Completed transfer state enum.
     */
    COMPLETED,
    /**
     * Terminated transfer state enum.
     */
    TERMINATED,
    /**
     * Error transfer state enum.
     */
    ERROR
}
